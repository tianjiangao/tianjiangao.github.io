import { readFile, readdir, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import matter from "gray-matter";
export async function readArticles(
  root,
  folder = resolve(root, "content/articles"),
) {
  await mkdir(folder, { recursive: true });
  const posts = [];
  const keys = new Set();
  for (const file of (await readdir(folder)).sort()) {
    if (!file.endsWith(".md")) continue;
    const { data, content } = matter(
      await readFile(resolve(folder, file), "utf8"),
    );
    if (data.draft === true) continue;
    if (data.draft !== false)
      throw new Error(`${file}: explicitly set draft: false to publish`);
    for (const key of ["slug", "title", "lang", "category", "summary"])
      if (typeof data[key] !== "string" || !data[key].trim())
        throw new Error(`${file}: missing ${key}`);
    if (
      !["zh", "en"].includes(data.lang) ||
      !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(data.slug)
    )
      throw new Error(`${file}: invalid language or slug`);
    const date =
      data.date instanceof Date
        ? data.date.toISOString().slice(0, 10)
        : String(data.date || "");
    if (
      !/^\d{4}-\d{2}-\d{2}$/.test(date) ||
      new Date(date).toISOString().slice(0, 10) !== date
    )
      throw new Error(`${file}: invalid date`);
    if (!content.trim()) throw new Error(`${file}: empty article`);
    const key = data.lang + "/" + data.slug;
    if (keys.has(key)) throw new Error(`${file}: duplicate article path`);
    keys.add(key);
    const post = {
      slug: data.slug,
      title: data.title,
      date,
      lang: data.lang,
      category: data.category,
      summary: data.summary,
      body: content,
    };
    if (data.translationKey) {
      if (typeof data.translationKey !== "string")
        throw new Error(`${file}: invalid translationKey`);
      post.translationKey = data.translationKey;
    }
    posts.push(post);
  }
  posts.sort(
    (a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug),
  );
  const translations = new Set();
  for (const p of posts)
    if (p.translationKey) {
      const key = p.lang + "/" + p.translationKey;
      if (translations.has(key))
        throw new Error(`Duplicate translationKey: ${key}`);
      translations.add(key);
    }
  const metadata = posts.map(({ body, ...meta }) => meta);
  await writeFile(
    resolve(root, "app/articles.generated.ts"),
    '// Generated by scripts/articles.mjs; edit content/articles/*.md instead.\nimport type { ArticleMeta } from "./article-types";\nexport const articles: ArticleMeta[] = ' +
      JSON.stringify(metadata, null, 2) +
      ";\n",
  );
  return posts;
}
